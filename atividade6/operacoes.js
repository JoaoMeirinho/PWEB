const numero1 = parseFloat(prompt("Digite o primeiro numero"));
const numero2 = parseFloat(prompt("Digite o segundo numero"));

const soma = numero1 + numero2;
const subtracao = numero1 - numero2;
const multiplicacao = numero1 * numero2;
const divisao = numero1 / numero2;
const resto = numero1 % numero2;

alert(`A soma dos numeros é ${soma}`);
alert(`A subtração dos numeros é ${subtracao}`);
alert(`A multiplicação dos numeros é ${multiplicacao}`);
alert(`A divisão dos numeros é ${divisao}`);
alert(`O resto da divisão dos numeros é ${resto}`);